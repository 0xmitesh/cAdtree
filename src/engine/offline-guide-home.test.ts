test('a new project, a new workspace or a changed status rewrites the Index and not the Readme', async () => {
  const f = await homeFixture();
  await refreshHomeGuide(f.home, { now: at('2026-11-16T10:00:00.000Z') });
  const state = await openHome(f.home);
  const client = state.workspaces.find((e) => e.name === 'Client ABC')!;

  await createProject(client.workspace!.root, 'Spindle');
  f.writes.length = 0;
  const afterProject = await refreshHomeGuide(f.home, { now: at('2026-11-16T11:00:00.000Z') });
  assert.deepEqual(afterProject.written, [INDEX]);
  assert.deepEqual(guideWrites(f), [`Cadtree/${INDEX}`]);
  let index = await read(f, INDEX);
  assert.match(index, /Generated: 2026-11-16T11:00:00\.000Z/);
  assert.match(index, /Projects: 3/);
  assert.match(index, /Folder: Client ABC\/projects\/Spindle/);

  await createHomeWorkspace(f.home, 'AutoCAD');
  f.writes.length = 0;
  const afterWorkspace = await refreshHomeGuide(f.home, { now: at('2026-11-16T12:00:00.000Z') });
  assert.deepEqual(afterWorkspace.written, [INDEX]);
  index = await read(f, INDEX);
  assert.match(index, /WORKSPACES \(3\)/);
  assert.match(index, /\r\n {4}AutoCAD\r\n {8}Folder: AutoCAD\r\n/);

  // A workspace that stops opening changes the Index too.
  await (await f.home.getDirectory(['Personal SolidWorks'])).removeEntry(['.cadtree-workspace.json']);
  const afterDamage = await refreshHomeGuide(f.home, { now: at('2026-11-16T13:00:00.000Z') });
  assert.equal(afterDamage.status, 'written');
  assert.deepEqual(afterDamage.written, [INDEX]);
  assert.match(await read(f, INDEX), /Personal SolidWorks\r\n {8}Folder: Personal SolidWorks\r\n {8}Workspace ID: [^\r\n]+\r\n {8}Status: damaged/);
});

test('a deleted or hand-edited guide file is written again; a correct one is left alone', async () => {
  const f = await homeFixture();
  await refreshHomeGuide(f.home, { now: at('2026-11-16T10:00:00.000Z') });
  const index = await read(f, INDEX);
  const readme = await read(f, README);
  await f.home.removeEntry([README]);
  await f.home.writeFileText([INDEX], 'edited by hand\r\n');
  f.writes.length = 0;
  const result = await refreshHomeGuide(f.home, { now: at('2026-11-16T10:00:00.000Z') });
  assert.deepEqual([...result.written].sort(), [INDEX, README]);
  assert.equal(await read(f, README), readme);
  assert.equal(await read(f, INDEX), index);
  // A Readme that differs (an older format) is replaced.
  await f.home.writeFileText([README], readme.replace('Guide format: 2', 'Guide format: 0'));
  f.writes.length = 0;
  assert.deepEqual((await refreshHomeGuide(f.home)).written, [README]);
  assert.equal(await read(f, README), readme);
});

test('a write failure yields partial, never throws, and the other file is still written', async () => {
  const f = await homeFixture();
  f.home.setHooks({ onBeforeWrite: (full) => { if (full.endsWith(INDEX)) throw new Error('disk full'); } });
  const warnings: unknown[][] = [];
  const realWarn = console.warn;
  console.warn = (...args: unknown[]) => { warnings.push(args); };
  let result;
  try {
    result = await refreshHomeGuide(f.home);
  } finally {
    console.warn = realWarn;
  }
  assert.equal(result.status, 'partial');
  assert.deepEqual(result.written, [README]);
  assert.deepEqual(result.failed.map((item) => item.path), [INDEX]);
  assert.match(result.failed[0]!.error, /disk full/);
  assert.equal(warnings.length, 1);
  assert.equal(await f.home.hasFile([INDEX]), false);
  // The home still opens as before.
  assert.equal((await openHome(f.home)).workspaces.length, 2);
});

test('a read-back mismatch is a failure', async () => {
  const f = await homeFixture();
  let tampered = false;
  f.home.setHooks({
    onAfterWrite: async (full) => {
      if (!full.endsWith(README) || tampered) return;
      tampered = true;
      await f.home.writeFileText([README], 'changed behind our back\r\n');
    },
  });
  const result = await quiet(() => refreshHomeGuide(f.home));
  assert.equal(result.status, 'partial');
  assert.deepEqual(result.failed.map((item) => item.path), [README]);
  assert.match(result.failed[0]!.error, /Read-back did not match/);
  assert.deepEqual(result.written, [INDEX]);
});

test('a bad home is skipped without any write and without throwing', async () => {
  // No home at all.
  const empty = new InMemoryFileSystemAdapter('Cadtree');
  const writes: string[] = [];
  empty.setHooks({ onBeforeWrite: (full) => { writes.push(full); } });
  const none = await quiet(() => refreshHomeGuide(empty));
  assert.equal(none.status, 'skipped');
  assert.deepEqual(none.written, []);

  // A damaged identity record (checksum mismatch).
  const f = await homeFixture();
  const identity = JSON.parse(await read(f, '.cadtree-home.json'));
  f.writes.length = 0;
  await f.home.writeFileText(['.cadtree-home.json'], JSON.stringify({ ...identity, name: 'Tampered' }, null, 2));
  f.writes.length = 0;
  const tampered = await quiet(() => refreshHomeGuide(f.home));
  assert.equal(tampered.status, 'skipped');
  assert.match(tampered.reason ?? '', /checksum/i);

  // An identity without an ID, and unreadable JSON.
  await f.home.writeFileText(['.cadtree-home.json'], '{}');
  assert.equal((await quiet(() => refreshHomeGuide(f.home))).status, 'skipped');
  await f.home.writeFileText(['.cadtree-home.json'], '{ not json');
  f.writes.length = 0;
  assert.equal((await quiet(() => refreshHomeGuide(f.home))).status, 'skipped');
  assert.deepEqual(guideWrites(f), []);

  // The registry folder is gone.
  const g = await homeFixture();
  await g.home.removeEntry(['.cadtree-home'], { recursive: true });
  g.writes.length = 0;
  assert.equal((await quiet(() => refreshHomeGuide(g.home))).status, 'skipped');
  assert.deepEqual(g.writes, []);

  // A read-only home.
  const h = await homeFixture();
  h.home.setHooks({ writePermission: 'denied' });
  h.writes.length = 0;
  const denied = await refreshHomeGuide(h.home);
  assert.equal(denied.status, 'skipped');
  assert.match(denied.reason ?? '', /not writable/);
  assert.deepEqual(h.writes, []);
  assert.deepEqual(writes, []);
});

test('refresh takes the home lock (home:<homeId>) and simultaneous refreshes are serialised', async () => {
  const f = await homeFixture();
  let release!: () => void;
  const gate = new Promise<void>((resolve) => { release = resolve; });
  const holder = withProjectWriterLock(`home:${f.homeId}`, () => gate);
  f.writes.length = 0;
  const pending = refreshHomeGuide(f.home);
  await new Promise((resolve) => setTimeout(resolve, 25));
  assert.deepEqual(f.writes, [], 'waits for the lock before writing');
  release();
  await holder;
  assert.deepEqual([...(await pending).written].sort(), [INDEX, README]);

  const g = await homeFixture();
  const results = await Promise.all([refreshHomeGuide(g.home), refreshHomeGuide(g.home)]);
  assert.deepEqual(results.map((r) => r.status), ['written', 'written']);
  assert.deepEqual([...results[0]!.written].sort(), [INDEX, README]);
  assert.deepEqual(results[1]!.written, [], 'the second refresh finds the files the first one wrote');
  assert.equal(guideWrites(g).length, 2);
});

