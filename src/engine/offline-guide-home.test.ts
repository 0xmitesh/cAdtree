const README = '_README cAdtree.txt';
const INDEX = '_INDEX cAdtree.txt';
const GENERATED = '2026-11-16T09:30:00.000Z';
const at = (iso: string) => () => new Date(iso);

interface HomeFixture {
  home: InMemoryFileSystemAdapter;
  writes: string[];
  homeId: string;
}

/** A home with workspace "Client ABC" (two projects) and an empty workspace "Personal SolidWorks". */
async function homeFixture(): Promise<HomeFixture> {
  const home = new InMemoryFileSystemAdapter('Cadtree');
  const writes: string[] = [];
  home.setHooks({ onBeforeWrite: (full) => { writes.push(full); } });
  const state = await createHome(home);
  const client = await createHomeWorkspace(home, 'Client ABC');
  await createProject(client.workspace.root, 'Packaging Gripper');
  await createProject(client.workspace.root, 'Valve housing');
  await createHomeWorkspace(home, 'Personal SolidWorks');
  return { home, writes, homeId: state.identity.homeId };
}

const guideWrites = (f: HomeFixture) => f.writes.filter((w) => w.endsWith(README) || w.endsWith(INDEX));
const read = (f: HomeFixture, name: string) => f.home.readFileText([name]);

function assertPlainText(text: string) {
  assert.ok(text.endsWith('\r\n') && !text.endsWith('\r\n\r\n'), 'ends with a single CRLF');
  assert.ok(!text.includes('﻿'), 'no BOM');
  assert.ok(!/(?<!\r)\n/.test(text), 'no lone LF');
  assert.ok(!/\r(?!\n)/.test(text), 'no lone CR');
  for (const line of text.split('\r\n')) assert.equal(line, line.replace(/[ \t]+$/, ''), `trailing whitespace: "${line}"`);
}

async function quiet<T>(run: () => Promise<T>): Promise<T> {
  const realWarn = console.warn;
  console.warn = () => {};
  try {
    return await run();
  } finally {
    console.warn = realWarn;
  }
}

/** What openHome reports, without the live adapters (which can't be compared). */
async function homeSummary(home: InMemoryFileSystemAdapter) {
  const state = await openHome(home);
  return {
    homeId: state.identity.homeId,
    workspaces: state.workspaces.map((entry) => ({
      key: entry.key, name: entry.name, directory: entry.directory, recordedDirectory: entry.recordedDirectory,
      workspaceId: entry.workspaceId, status: entry.status, issues: entry.issues,
      projects: entry.workspace?.projects.map((p) => ({
        containerPath: p.containerPath, projectId: p.projectId, name: p.name, status: p.status, issues: p.issues,
      })),
    })),
  };
}

