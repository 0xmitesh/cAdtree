// The app refreshes the offline guide (CLAUDE.md §2) after each successful operation, fire-and-forget, so every
// positive check waits for the file. Negative checks wait for a settled app plus a short pause.
Object.assign(globalThis, { indexedDB });
afterEach(async () => {
  cleanup();
  await clearAllConvenienceMetadata();
  Reflect.deleteProperty(window, "showDirectoryPicker");
});
const README = "_README cAdtree.txt";
const INDEX = "_INDEX cAdtree.txt";
const MAP = "_MAP cAdtree.txt";
const notes = { problem: "", modification: "", observations: "" };
const settle = () => new Promise((resolve) => setTimeout(resolve, 150));
const idle = (ui: ReturnType<typeof render>) => waitFor(() => assert.equal(appBusy(ui), false));
const readText = (root: InMemoryFileSystemAdapter, path: string[]) => root.readFileText(path);
const hasFile = (root: InMemoryFileSystemAdapter, path: string[]) => root.hasFile(path);

async function seeded() {
  const home = new InMemoryFileSystemAdapter("Cadtree");
  await createHome(home);
  const { workspace } = await createHomeWorkspace(home, "Workbench");
  const root = workspace.root as InMemoryFileSystemAdapter;
  const project = await createProject(root, "Actuator");
  const main = project.workingFolders["branch-main"]!;
  await main.writeFileBytes(["Part.SLDPRT"], new Uint8Array([1, 2, 3]));
  const first = await captureRevision(main, project.vaultDir, {
    branchId: "branch-main",
    summary: "Original housing",
    notes,
    workingFolders: project.workingFolders,
  });
  const container = project.record.containerPath.split("/");
  return { home, root, project, main, first, container, mapPath: [...container, MAP] };
}
async function openProject(ui: ReturnType<typeof render>, home: InMemoryFileSystemAdapter) {
  await openHomeWorkspace(ui, home);
  fireEvent.click(ui.getByRole("button", { name: "Open project" }));
  await idle(ui);
  await waitFor(() => assert.ok(ui.getByRole("region", { name: "Project context" })));
}
const changesPage = (ui: ReturnType<typeof render>) =>
  within([...ui.container.querySelectorAll<HTMLElement>(".changes-page")].find((page) => !page.parentElement!.hidden)!);
async function scanMain(ui: ReturnType<typeof render>) {
  fireEvent.click(within(ui.getByRole("navigation")).getByRole("button", { name: "Changes" }));
  await waitForScan(ui);
  await waitFor(() => assert.ok(ui.getByRole("heading", { name: "1 changed file" })));
}

test("creating a home writes its Readme and Index; opening a writable home does the same, and opening never writes a project", async () => {
  const created = new InMemoryFileSystemAdapter("Fresh Cadtree");
  Object.assign(window, { showDirectoryPicker: async () => nativeDirectory(created) });
  let ui = render(<App />);
  fireEvent.click(ui.getByRole("button", { name: "Start my Cadtree home" }));
  await completeHomeAddress(ui, "D:\\Fresh Cadtree");
  await idle(ui);
  await waitFor(async () => assert.equal(await hasFile(created, [INDEX]), true));
  assert.match(await readText(created, [README]), /generated by cAdtree/i);
  assert.match(await readText(created, [INDEX]), /WORKSPACES \(0\)/);
  cleanup();

  // An existing home from before the guide existed gets its files when it is opened; its projects are left alone.
  const f = await seeded();
  assert.equal(await hasFile(f.home, [README]), false);
  ui = render(<App />);
  await openTestHome(ui, f.home);
  await waitFor(async () => assert.equal(await hasFile(f.home, [INDEX]), true));
  assert.equal(await hasFile(f.home, [README]), true);
  fireEvent.click(ui.getByRole("button", { name: "Open workspace" }));
  await idle(ui);
  fireEvent.click(ui.getByRole("button", { name: "Open project" }));
  await idle(ui);
  await settle();
  assert.equal(await hasFile(f.root, f.mapPath), false, "opening and browsing a project writes no Map");
  assert.equal(await hasFile(f.root, [...f.container, "vault", "revisions", `${f.first.revision.manifest.revisionId}.txt`]), false);
});

test("creating a workspace and a project writes the home Index, and the project's Map", async () => {
  const home = new InMemoryFileSystemAdapter("Cadtree");
  await createHome(home);
  const ui = render(<App />);
  await openTestHome(ui, home);
  fireEvent.click(ui.getByRole("button", { name: /Create workspace/ }));
  let dialog = within(ui.getByRole("dialog"));
  fireEvent.change(dialog.getByRole("textbox", { name: "Workspace name" }), { target: { value: "Workbench" } });
  fireEvent.click(dialog.getByRole("button", { name: "Create workspace" }));
  await waitFor(() => assert.ok(!ui.queryByRole("dialog")));
  await idle(ui);
  await waitFor(async () => assert.match(await readText(home, [INDEX]), /Workbench/));
  assert.ok(await hasFile(home, [README]));

  fireEvent.click(ui.getByRole("button", { name: "Create project" }));
  dialog = within(ui.getByRole("dialog", { name: "Create project" }));
  fireEvent.change(dialog.getByRole("textbox", { name: "Project name" }), { target: { value: "New design" } });
  fireEvent.click(dialog.getByRole("button", { name: "Create project" }));
  await waitFor(() => assert.ok(!ui.queryByRole("dialog")));
  await idle(ui);
  const root = (await openHome(home)).workspaces[0].workspace!.root as InMemoryFileSystemAdapter;
  const container = (await openWorkspace(root)).projects[0].containerPath.split("/");
  await waitFor(async () => assert.match(await readText(root, [...container, MAP]), /Project: New design/));
  await waitFor(async () => assert.match(await readText(home, [INDEX]), /New design/));
  assert.match(await readText(home, [INDEX]), /_MAP cAdtree\.txt/);
});

test("saving a version refreshes the Map and writes the version listing; a failed save does neither", async () => {
  const f = await seeded();
  const ui = render(<App />);
  await openProject(ui, f.home);
  await f.main.writeFileBytes(["Part.SLDPRT"], new Uint8Array([3, 2]));
  await scanMain(ui);
  fireEvent.change(changesPage(ui).getByRole("textbox", { name: /Version summary/ }), { target: { value: "Main draft" } });
  // The working folder changes after the review: the save is refused as stale, nothing is published.
  await f.main.writeFileBytes(["Late.SLDPRT"], new Uint8Array([9]));
  fireEvent.click(changesPage(ui).getByRole("button", { name: "Save version" }));
  await idle(ui);
  await waitFor(() => assert.ok(ui.getByRole("button", { name: "confirm this file set" })));
  await settle();
  assert.equal((await openExistingVault(f.project.vaultDir)).revisions.length, 1);
  assert.equal(await hasFile(f.root, f.mapPath), false, "a failed save does not refresh the guide");
  assert.equal(await hasFile(f.root, [...f.container, "vault", "revisions", `${f.first.revision.manifest.revisionId}.txt`]), false);

  // Confirm the new file set and save for real.
  fireEvent.click(ui.getByRole("button", { name: "confirm this file set" }));
  fireEvent.click(changesPage(ui).getByRole("button", { name: "Save version" }));
  await waitFor(async () => assert.equal((await openExistingVault(f.project.vaultDir)).revisions.length, 2));
  await idle(ui);
  const revisions = (await openExistingVault(f.project.vaultDir)).revisions;
  const second = revisions[1].manifest.revisionId;
  await waitFor(async () => assert.match(await readText(f.root, f.mapPath), /Main draft/));
  const map = await readText(f.root, f.mapPath);
  assert.match(map, new RegExp(revisions[0].manifest.revisionId));
  assert.match(map, new RegExp(second));
  for (const revision of revisions) {
    const listing = await readText(f.root, [...f.container, "vault", "revisions", `${revision.manifest.revisionId}.txt`]);
    assert.match(listing, /SHA-256/i);
  }
});

test("creating a design case and hiding it refresh the Map", async () => {
  const f = await seeded();
  const ui = render(<App />);
  await openProject(ui, f.home);
  fireEvent.click(ui.getByRole("button", { name: "History" }));
  fireEvent.click(ui.getByRole("button", { name: /V1: Original housing/ }));
  fireEvent.click(ui.getByRole("button", { name: "Create design case from this version" }));
  await waitFor(() => assert.ok(ui.queryByRole("dialog")));
  const dialog = within(ui.getByRole("dialog"));
  fireEvent.change(dialog.getByRole("textbox", { name: "Case name" }), { target: { value: "Lighter collar" } });
  fireEvent.change(dialog.getByRole("textbox", { name: "Engineering reason" }), { target: { value: "Save weight" } });
  fireEvent.click(dialog.getByRole("button", { name: "Create design case" }));
  await waitFor(() => assert.ok(!ui.queryByRole("dialog")));
  await idle(ui);
  await waitFor(async () => assert.match(await readText(f.root, f.mapPath), /Lighter collar/));
  const map = await readText(f.root, f.mapPath);
  assert.match(map, /Working folder: working\/Lighter collar/);
  assert.match(map, /Status: active/);
  assert.doesNotMatch(map, /Status: hidden/);

  // The new case is the working case: switch back to Main, then hide it.
  const branch = (await openExistingVault(f.project.vaultDir)).branches.find((b) => b.name === "Lighter collar")!;
  assert.equal(currentBranchId(ui), branch.branchId);
  await selectBranch(ui, "branch-main");
  fireEvent.click(ui.getByRole("button", { name: "History" }));
  fireEvent.click(ui.container.querySelector(".history-design-cases > summary")!);
  fireEvent.click(ui.getByRole("button", { name: "Hide case Lighter collar" }));
  fireEvent.click(within(ui.getByRole("dialog", { name: "Hide design case" })).getByRole("button", { name: "Hide case" }));
  await waitFor(async () => assert.match(await readText(f.root, f.mapPath), /Status: hidden/));
  await idle(ui);
});

test("bringing a workspace into the home rewrites the Maps its projects were copied with", async () => {
  const home = new InMemoryFileSystemAdapter("Cadtree");
  await createHome(home);
  const original = new InMemoryFileSystemAdapter("cam 2");
  await createWorkspace(original);
  const project = await createProject(original, "Actuator");
  const main = project.workingFolders["branch-main"]!;
  await main.writeFileBytes(["Part.SLDPRT"], new Uint8Array([1]));
  await captureRevision(main, project.vaultDir, { branchId: "branch-main", summary: "Original", notes, workingFolders: project.workingFolders });
  const container = project.record.containerPath.split("/");
  await original.writeFileText([...container, MAP], "STALE MAP FROM THE ORIGINAL\r\n");

  const ui = render(<App />);
  await openTestHome(ui, home);
  Object.assign(window, { showDirectoryPicker: async () => nativeDirectory(original) });
  fireEvent.click(ui.getByText("Home options"));
  fireEvent.click(ui.getByRole("button", { name: "Import existing workspace" }));
  fireEvent.click(ui.getByRole("button", { name: "Choose workspace folder" }));
  await waitFor(() => assert.match(ui.container.textContent!, /Original workspace retained unchanged/));
  await idle(ui);
  const copy = (await openHome(home)).workspaces[0].workspace!.root as InMemoryFileSystemAdapter;
  const copied = (await openWorkspace(copy)).projects[0].containerPath.split("/");
  await waitFor(async () => assert.match(await readText(copy, [...copied, MAP]), /Project: Actuator/));
  assert.doesNotMatch(await readText(copy, [...copied, MAP]), /STALE/);
  assert.match(await readText(original, [...container, MAP]), /STALE/, "the original is never touched");
});
