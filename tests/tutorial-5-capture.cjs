// Direct current-App screenshots with disposable native-handle facades.
// Reproduce after npm run build: node tests/tutorial-5-capture.cjs
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { build } = require('esbuild');
const { chromium } = require('@playwright/test');
const root = path.resolve(__dirname, '..');
const artifacts = path.join(root, 'artifacts', 'tutorial-5');
const assets = path.join(root, 'public', 'tutorials', 'compare-apply-recover');
const archiveOnly = process.argv.includes('--archive-only');

(async () => {
  fs.mkdirSync(artifacts, { recursive: true }); fs.mkdirSync(assets, { recursive: true });
  const entry = `import {createRoot} from 'react-dom/client';import App from './src/App';
import {compareApplyRecoverSample} from './tests/compare-apply-recover-sample';
import {nativeDirectory} from './tests/native-fs';
import {createTestAuthController} from './tests/test-auth';
import {resolveManagedProject} from './src/engine/workspace-service';
import {inventorySignature,readVerifiedInventory} from './src/engine/copy-service';
async function start(){const s=await compareApplyRecoverSample();let picks=0;
const current=()=>resolveManagedProject(s.workspace.root,s.project.record.containerPath);
const signature=async dir=>inventorySignature(await readVerifiedInventory(dir));
Object.assign(window,{showDirectoryPicker:async()=>{if(++picks>1)throw Error('Unexpected folder picker');return nativeDirectory(s.home);},tutorialSample:{...s,current,signature,inspect:async()=>{const p=await current();return {revisions:p.vaultState.revisions.map(r=>({id:r.manifest.revisionId,number:r.manifest.displayNumber,parent:r.manifest.parentRevisionId,branch:r.manifest.branchId,files:r.manifest.files,directories:r.manifest.directories})),applications:p.vaultState.applicationOperations?.map(o=>({status:o.status,source:o.record?.plan.sourceRevisionId,actions:o.record?.plan.actions.map(a=>({path:a.path,operation:a.operation}))})),main:await readVerifiedInventory(s.main),source:await signature(s.caseFolder),lifecycle:p.vaultState.caseLifecycles?.[s.caseId],picks};},recoveries:async()=>{const p=await current(),parent=await s.workspace.root.getDirectory([...p.record.containerPath.split('/'),'recoveries']);const results=[];for(const e of await parent.listEntries())if(e.kind==='directory')results.push({name:e.name,inventory:await readVerifiedInventory(await parent.getDirectory([e.name]))});return results;}}});createRoot(document.getElementById('root')).render(<App auth={createTestAuthController().adapter}/>);}
start().catch(e=>{document.body.textContent=String(e.stack||e);console.error(e);});`;
  const bundle = await build({ stdin: { contents: entry, loader: 'tsx', resolveDir: root }, bundle: true, write: false, format: 'iife', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' } });
  const cssDir = path.join(root, 'dist', 'assets');
  const css = fs.readFileSync(path.join(cssDir, fs.readdirSync(cssDir).find(n => n.endsWith('.css'))), 'utf8');
  const html = path.join(artifacts, 'capture.html');
  fs.writeFileSync(html, '<!doctype html><html><head><meta charset="utf-8"><style>' + css + '</style></head><body><div id="root"></div><script>' + bundle.outputFiles[0].text.replaceAll('</script', '<\\/script') + '</script></body></html>');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1024, height: 1200 }, deviceScaleFactor: 3 });
  const errors = [], screenshots = [];
  page.on('pageerror', e => errors.push(e.message));
  const dismiss = async () => { if (await page.locator('dialog[open]').count()) return; const b = page.getByRole('button', { name: 'Dismiss message', exact: true }); while (await b.count()) await b.first().click(); };
  const idle = async () => { await page.waitForFunction(() => document.querySelector('main')?.getAttribute('aria-busy') === 'false'); await dismiss(); };
  const focus = async b => { await page.keyboard.press('Tab'); await b.focus(); };
  const capture = async (locator, name) => {
    if (archiveOnly && !name.startsWith('step-7-')) return;
    await dismiss(); await locator.scrollIntoViewIfNeeded();
    const b = await locator.boundingBox();
    const inset = await locator.evaluate(e => e.tagName === 'DIALOG') ? 8 : -8;
    screenshots.push({ name, width: b.width - inset * 2, height: b.height - inset * 2 });
    await page.screenshot({ path: path.join(assets, name + '.png'), clip: { x: Math.max(0, b.x + inset), y: Math.max(0, b.y + inset), width: b.width - inset * 2, height: b.height - inset * 2 } });
  };
  const between = async (first, last, name) => {
    if (archiveOnly && !name.startsWith('step-7-')) return;
    await dismiss(); await first.scrollIntoViewIfNeeded();
    const a = await first.boundingBox(), b = await last.boundingBox();
    const x = Math.min(a.x, b.x), right = Math.max(a.x + a.width, b.x + b.width);
    screenshots.push({ name, width: right - x + 16, height: b.y + b.height - a.y + 16 });
    await page.screenshot({ path: path.join(assets, name + '.png'), clip: { x: x - 8, y: a.y - 8, width: right - x + 16, height: b.y + b.height - a.y + 16 } });
  };
  const fileStates = files => files.map(f => [f.path, f.size, f.sha256]).sort((a, b) => a[0].localeCompare(b[0]));
  try {
    await page.goto(pathToFileURL(html).href);
    await page.addStyleTag({ content: '.modal, .panel, .history-canvas, .revision-detail { box-shadow: none !important; }' });
    await page.getByRole('button', { name: 'Open my Cadtree home', exact: true }).click();
    await page.getByRole('textbox', { name: 'Cadtree home folder address' }).fill('D:\\Cadtree');
    await page.getByRole('button', { name: 'Complete setup', exact: true }).click(); await idle();
    await page.getByRole('button', { name: 'Open workspace', exact: true }).click(); await idle();
    await page.getByRole('button', { name: 'Open project', exact: true }).click(); await idle();
    const nav = page.getByRole('navigation', { name: 'Primary navigation' });
    const ids = await page.evaluate(() => ({ source: window.tutorialSample.source.manifest.revisionId, destination: window.tutorialSample.destination.manifest.revisionId, base: window.tutorialSample.baseline.manifest.revisionId, caseId: window.tutorialSample.caseId }));
    const initial = await page.evaluate(() => window.tutorialSample.inspect());
    const beforeCompare = await page.evaluate(() => window.tutorialSample.signature(window.tutorialSample.home));
    await page.getByRole('button', { name: /Rev 005: Reinforced mounting rib/ }).click();
    const compare = page.getByRole('button', { name: 'Compare', exact: true });
    await focus(compare); await capture(page.locator('.revision-detail .detail-header'), 'step-2-open-compare');
    await compare.click();
    const comparison = page.getByRole('dialog', { name: 'Compare saved revisions', exact: true });
    await comparison.getByRole('combobox', { name: 'From revision', exact: true }).selectOption(ids.destination);
    await comparison.getByRole('combobox', { name: 'To revision', exact: true }).selectOption(ids.source);
    await focus(comparison.getByRole('combobox', { name: 'From revision', exact: true }));
    await capture(comparison.locator('.comparison-selectors'), 'step-2-choose-states');
    assert.match(await comparison.getByRole('status', { name: 'Comparison counts' }).innerText(), /1 added\s+1 deleted\s+2 modified\s+1 unchanged/);
    await comparison.getByText('Overall engineering notes', { exact: true }).click();
    await between(comparison.locator('.comparison-counts'), comparison.getByRole('article', { name: 'Modified: Bracket.SLDPRT', exact: true }), 'step-2-file-differences');
    // Include the recorded engineering notes in the result capture without a tall whole-dialog image.
    await comparison.getByText('Overall engineering notes', { exact: true }).click();
    await capture(comparison.getByRole('region', { name: 'Overall engineering notes' }), 'step-2-engineering-notes');
    await comparison.getByRole('button', { name: 'Swap', exact: true }).click();
    assert.equal(await comparison.getByRole('combobox', { name: 'From revision', exact: true }).inputValue(), ids.source);
    await comparison.getByRole('button', { name: 'Swap', exact: true }).click();
    await comparison.getByRole('button', { name: 'Close comparison', exact: true }).click();
    assert.equal(await page.evaluate(() => window.tutorialSample.signature(window.tutorialSample.home)), beforeCompare);
    const review = page.getByRole('button', { name: 'Review changes to apply', exact: true });
    await focus(review); await between(page.locator('.revision-detail .detail-header'), page.locator('.detail-preview-action'), 'step-4-open-review');
    await review.click();
    const preview = page.getByRole('dialog', { name: /^Review changes to apply/ });
    assert.equal(await preview.getByRole('checkbox', { checked: true }).count(), 0);
    await capture(preview.locator('.preview-endpoints'), 'step-4-source-destination');
    for (const name of ['Select source modification: Bracket.SLDPRT', 'Select source addition: Rib.SLDPRT', 'Select source deletion: Spacer.SLDPRT']) await preview.getByRole('checkbox', { name, exact: true }).check();
    await preview.getByRole('textbox', { name: 'Engineering reason for proposed application', exact: true }).fill('Adopt the lighter bracket and reinforcement while retaining Main\'s mounting update.');
    await capture(preview.locator('.preview-candidates'), 'step-4-selected-actions');
    await preview.getByRole('button', { name: 'Prepare application', exact: true }).click(); await idle();
    const confirmation = page.getByRole('dialog', { name: 'Confirm working-file application', exact: true });
    assert.equal(await confirmation.getByRole('button', { name: 'Apply confirmed changes', exact: true }).isDisabled(), true);
    await between(confirmation.locator('p').filter({ hasText: /Project: Bracket Assembly/ }).first(), confirmation.locator('.application-actions'), 'step-5-confirm-actions');
    await confirmation.getByRole('checkbox', { name: 'I have saved and closed relevant CAD documents and confirm this destination.', exact: true }).check();
    const apply = confirmation.getByRole('button', { name: 'Apply confirmed changes', exact: true });
    await focus(apply); await between(confirmation.locator('.file-choice'), confirmation.locator('.modal-actions'), 'step-5-confirm-apply');
    await apply.click(); await idle();
    const completed = page.getByRole('dialog', { name: 'Application completed', exact: true });
    await capture(completed, 'step-5-applied-working-files');
    const applied = await page.evaluate(() => window.tutorialSample.inspect());
    assert.equal(applied.revisions.length, 6, 'Apply does not save a revision');
    assert.equal(applied.source, initial.source, 'Apply does not change the source case');
    assert.equal(applied.main.files.find(f => f.path === 'Mount.SLDPRT').sha256, initial.main.files.find(f => f.path === 'Mount.SLDPRT').sha256, 'Main-only update retained');
    for (const name of ['Bracket.SLDPRT', 'Rib.SLDPRT']) assert.equal(applied.main.files.find(f => f.path === name).sha256, initial.revisions.find(r => r.number === 5).files.find(f => f.path === name).sha256);
    assert.equal(applied.main.files.some(f => f.path === 'Spacer.SLDPRT'), false);
    await completed.getByRole('button', { name: 'Return to History', exact: true }).click();
    await page.getByRole('button', { name: 'Review and save revision', exact: true }).click();
    await page.getByRole('button', { name: 'Scan for changes', exact: true }).click(); await idle();
    await page.getByRole('textbox', { name: 'Revision summary' }).fill('Adopt lightweight bracket after review');
    await page.getByRole('button', { name: 'Save revision', exact: true }).click(); await idle();
    await nav.getByRole('button', { name: 'History', exact: true }).click();
    await page.getByRole('button', { name: /Rev 007: Adopt lightweight bracket after review/ }).click();
    await between(page.locator('.revision-detail .detail-header'), page.locator('.applied-from'), 'step-5-saved-main');
    const saved = await page.evaluate(() => window.tutorialSample.inspect());
    assert.equal(saved.revisions.find(r => r.number === 7).parent, ids.destination);
    assert.equal(saved.applications[0].status, 'captured');
    await page.getByRole('button', { name: /Rev 003: Reviewed baseline/ }).click();
    const restore = page.getByRole('button', { name: 'Restore project copy', exact: true });
    await focus(restore); await capture(page.locator('.recovery-bar'), 'step-6-restore-action');
    await restore.click(); await idle();
    const restoreDialog = page.getByRole('dialog', { name: 'Restore a complete project copy', exact: true });
    assert.equal(await restoreDialog.getByRole('checkbox', { name: 'Choose an external destination instead', exact: true }).isChecked(), false);
    await focus(restoreDialog.getByRole('button', { name: 'Restore copy', exact: true }));
    await capture(restoreDialog, 'step-6-restore-confirmation');
    const beforeRecovery = await page.evaluate(() => window.tutorialSample.signature(window.tutorialSample.main));
    await restoreDialog.getByRole('button', { name: 'Restore copy', exact: true }).click(); await idle();
    const recoveryNotice = page.locator('.history-page > .notice.success');
    await recoveryNotice.getByText('Recovery report', { exact: true }).click();
    await capture(recoveryNotice, 'step-6-restored-copy');
    const recovered = await page.evaluate(() => window.tutorialSample.recoveries());
    assert.equal(recovered.length, 1);
    assert.deepEqual(fileStates(recovered[0].inventory.files), fileStates(initial.revisions.find(r => r.number === 3).files));
    assert.deepEqual(recovered[0].inventory.directories, initial.revisions.find(r => r.number === 3).directories);
    assert.equal(await page.evaluate(() => window.tutorialSample.signature(window.tutorialSample.main)), beforeRecovery);
    await nav.getByRole('button', { name: 'History', exact: true }).click();
    assert.equal(await page.getByRole("region", { name: "Project context", exact: true }).getAttribute('data-branch-id'), 'branch-main');
    await page.locator('.history-design-cases > summary').click();
    const archive = page.getByRole('button', { name: 'Archive case Lightweight bracket', exact: true });
    await focus(archive); await capture(page.locator('.design-cases'), 'step-7-archive-action');
    await archive.click();
    const archiveDialog = page.getByRole('dialog', { name: 'Archive design case', exact: true });
    await focus(archiveDialog.getByRole('button', { name: 'Archive case', exact: true }));
    await capture(archiveDialog, 'step-7-archive-confirmation');
    await archiveDialog.getByRole('button', { name: 'Archive case', exact: true }).click(); await idle();
    await page.getByText('Archived cases (1)', { exact: true }).click();
    await capture(page.locator('.design-cases'), 'step-7-archived-case');
    const final = await page.evaluate(() => window.tutorialSample.inspect());
    assert.equal(final.lifecycle.status, 'archived'); assert.equal(final.revisions.length, 7); assert.equal(final.source, initial.source); assert.equal(final.picks, 1);
    assert.deepEqual(fileStates(final.main.files), fileStates(saved.main.files)); assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(artifacts, 'capture-verification.json'), JSON.stringify({ screenshots, ids, initial, applied, saved, recovered, final, errors }, null, 2));
    console.log(JSON.stringify({ screenshots: screenshots.length, initialRevisions: 6, appliedRevisions: applied.revisions.length, finalRevisions: final.revisions.length, sourceUnchanged: final.source === initial.source, recoveredFiles: recovered[0].inventory.files.length, lifecycle: final.lifecycle.status, picks: final.picks, errors }));
  } catch (e) {
    await page.screenshot({ path: path.join(artifacts, 'capture-debug.png'), fullPage: true });
    console.error(await page.locator('body').innerText()); throw e;
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
