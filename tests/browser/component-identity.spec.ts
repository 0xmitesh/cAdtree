import { pickComponent } from './file-picker';
import { test, expect } from '@playwright/test';

// Disposable origin-private folders. This qualifies browser workflow, not native CAD references.
for (const width of [1366, 390]) test(`actual App: confirmed rename and component history at ${width}px`, async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  const info = await page.evaluate(async (changedBytes) => {
    const fsPath = '/src/engine/fs-adapter.ts', homePath = '/src/engine/home-service.ts', workspacePath = '/src/engine/workspace-service.ts', revisionPath = '/src/engine/revision-service.ts';
    const [{ RealFileSystemAdapter }, homeService, workspaceService, { captureRevision }] = await Promise.all([import(fsPath), import(homePath), import(workspacePath), import(revisionPath)]);
    const root = await navigator.storage.getDirectory();
    const home = await root.getDirectoryHandle(`component-test-${crypto.randomUUID()}`, { create: true });
    const adapter = new RealFileSystemAdapter(home);
    await homeService.createHome(adapter);
    const workspace = await homeService.createHomeWorkspace(adapter, 'Engineering');
    const project = await workspaceService.createProject(workspace.workspace.root, 'Brake');
    const main = project.workingFolders['branch-main'];
    await main.writeFileText(['parts','caliper.SLDPRT'], 'saved original');
    const saved = await captureRevision(main, project.vaultDir, { branchId: 'branch-main', summary: 'Original component', notes: {problem:'Fit',modification:'Initial design',observations:''}, fileNotes:[{path:'parts/caliper.SLDPRT',problem:'Fit',modification:'Initial design',observations:''}], workingFolders: project.workingFolders });
    const componentId = saved.vaultState.components.revisions[saved.revision.manifest.revisionId].files[0].componentId;
    await main.removeEntry(['parts','caliper.SLDPRT']);
    await main.writeFileText(['parts','cliper.SLDPRT'], changedBytes ? 'new geometry or properties' : 'saved original');
    Object.assign(window, { showDirectoryPicker: async () => home, componentTestHome: home, componentTestMain: main, componentTestVault: project.vaultDir });
    return { componentId };
  }, width === 390);
  await page.getByRole('button', { name: 'Open my Cadtree home', exact: true }).click();
  await page.getByRole('textbox', { name: 'Cadtree home folder address' }).fill('D:\\Cadtree');
  await page.getByRole('button', { name: 'Complete setup', exact: true }).click();
  await page.getByRole('button', { name: 'Open workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Open project', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Changes', exact: true }).click();
  const identity = page.getByRole('region', { name: 'Component identity' });
  await expect(identity.getByText(width === 390 ? /Name and bytes may both have changed/ : /Possible rename:/)).toBeVisible();
  await identity.getByRole('combobox', { name: 'New path for parts/caliper.SLDPRT' }).selectOption('parts/cliper.SLDPRT');
  await identity.getByRole('button', { name: 'Confirm rename', exact: true }).click();
  await expect(identity.getByText('Confirmed rename: parts/caliper.SLDPRT → parts/cliper.SLDPRT')).toBeVisible();
  await identity.getByRole('button', { name: 'Cancel association' }).click();
  await expect(identity.getByText(/Confirmed rename:/)).toHaveCount(0);
  await identity.getByRole('button', { name: 'Confirm rename', exact: true }).click();
  await page.getByRole('textbox', { name: /Revision summary/ }).fill('Correct component filename');
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  await expect(page.getByRole('heading', { name: '0 changed files' })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'History', exact: true }).click();
  await pickComponent(page, info.componentId, 'parts/cliper.SLDPRT');
  await expect(page.getByRole('region', { name: 'Selected file history' }).getByText('Confirmed rename: parts/caliper.SLDPRT → parts/cliper.SLDPRT')).toBeVisible();
  await page.getByRole('button', { name: /^Rev 001: Original component/ }).click();
  await expect(page.getByRole('region', { name: 'Selected file history' }).getByText('parts/caliper.SLDPRT', { exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Project context" })).toHaveAttribute('data-branch-id', 'branch-main');
  await expect(page.getByRole('region', { name: 'Selected file history' }).getByText('Initial design', { exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/screenshots/component-history-${width}.png`, fullPage: true });
  await page.getByRole('navigation').getByRole('button', { name: 'Changes', exact: true }).click();
  await identity.getByText('Replace a component identity', { exact: true }).click();
  await identity.getByRole('button', { name: 'Treat as new component', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Treat as new component' });
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Confirm new component' }).click();
  await page.getByRole('textbox', { name: /Revision summary/ }).fill('Unrelated replacement');
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  const replacementId = await page.evaluate(async () => {
    const vaultPath = '/src/engine/vault-service.ts';
    const { openExistingVault } = await import(vaultPath);
    const state = await openExistingVault((window as any).componentTestVault);
    return state.components.revisions[state.branchHeads['branch-main']].files[0].componentId;
  });
  expect(replacementId).not.toBe(info.componentId);
  await page.reload();
  await page.getByRole('button', { name: /^Return to/ }).click();
  await page.getByRole('button', { name: 'Open workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Open project', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'History', exact: true }).click();
  await pickComponent(page, replacementId, 'parts/cliper.SLDPRT');
  await expect(page.getByRole('heading', { name: 'Unrelated replacement' })).toBeVisible();
  await pickComponent(page, info.componentId, 'parts/cliper.SLDPRT');
  await expect(page.getByRole('button', { name: 'Select file for export', exact: true })).toBeDisabled();
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
