import { test, expect } from '@playwright/test';

// Real browser handles in disposable storage; native CAD/folder dialogs are separate checks.
for (const width of [1366, 390]) test(`reference browser: branch/file/search intersection and exact downloads at ${width}px`, async ({ page }) => {
  test.setTimeout(60000);
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  const ids = await page.evaluate(async () => {
    const paths = ['/src/engine/fs-adapter.ts', '/src/engine/home-service.ts', '/src/engine/workspace-service.ts', '/src/engine/revision-service.ts', '/src/engine/references.ts', '/src/engine/scanner.ts', '/src/engine/vault-service.ts', '/src/engine/branch-state.ts'];
    const [{ RealFileSystemAdapter }, homeService, workspaceService, { captureRevision }, refs, { scanBranchChanges }, { openExistingVault }, { getBranchBaseline }] = await Promise.all(paths.map(path => import(path)));
    const root = await navigator.storage.getDirectory();
    const home = await root.getDirectoryHandle(`reference-browser-${crypto.randomUUID()}`, { create: true });
    const adapter = new RealFileSystemAdapter(home);
    await homeService.createHome(adapter);
    const workspace = await homeService.createHomeWorkspace(adapter, 'Engineering');
    let project = await workspaceService.createProject(workspace.workspace.root, 'Actuator');
    const main = project.workingFolders['branch-main'];
    for (const file of ['A.SLDPRT', 'B.SLDPRT', 'notes.txt']) await main.writeFileText([file], file);
    const author = { id: 'test-engineer-1', displayName: 'Test Engineer' };
    const metadata = (title: string) => ({ title, description: title + ' description', tags: ['fit'] });
    let state = await refs.importReferenceAttachment(project.vaultDir, project.record.projectId, new File([new Uint8Array([0, 255, 13, 10, 128])], 'Alpha.txt'), metadata('Alpha requirement'), undefined, { savedBy: author });
    const alpha = state.references.library[0];
    state = await refs.importReferenceAttachment(project.vaultDir, project.record.projectId, new File(['Beta one'], 'Beta.txt'), metadata('Beta requirement'));
    const beta = state.references.library[1];
    state = await refs.importReferenceAttachment(project.vaultDir, project.record.projectId, new File(['Project brief'], 'Brief.txt'), metadata('Project brief'));
    const brief = state.references.library[2];
    await refs.updateProjectReference(project.vaultDir, project.record.projectId, brief.referenceId, { projectVersionId: brief.versions[0].versionId });
    const link = (ref: typeof alpha, path: string, versionId = ref.versions[0].versionId) => ({ referenceId: ref.referenceId, versionId, locator: '', explanation: '', component: { kind: 'pending', path } });
    const save = async (branchId: string, explicit: ReturnType<typeof link>[], summary: string) => {
      state = await openExistingVault(project.vaultDir);
      const scan = await scanBranchChanges(project.workingFolders[branchId], branchId, getBranchBaseline(state, branchId));
      return captureRevision(project.workingFolders[branchId], project.vaultDir, { branchId, summary, notes: { problem: '', modification: '', observations: '' }, workingFolders: project.workingFolders, referenceReview: refs.createReferenceReview(state, scan, explicit) });
    };
    const first = await save('branch-main', [link(alpha, 'A.SLDPRT'), link(beta, 'B.SLDPRT')], 'Main baseline');
    const partB = first.vaultState.components.revisions[first.revision.manifest.revisionId].files.find((file: { path: string }) => file.path === 'B.SLDPRT').componentId;
    project = await workspaceService.createManagedBranch(workspace.workspace.root, project.record.containerPath, { sourceRevisionId: first.revision.manifest.revisionId, name: 'Alternative', reason: 'Explore B' });
    const alternativeId = project.createdBranchId;
    await save(alternativeId, [link(alpha, 'B.SLDPRT')], 'Alternative B source');
    state = await refs.importReferenceAttachment(project.vaultDir, project.record.projectId, new File(['Alpha two'], 'Alpha updated.txt'), metadata('Alpha requirement'), alpha.referenceId, { savedBy: author });
    await save(alternativeId, [link(alpha, 'B.SLDPRT', state.references.library[0].versions[1].versionId)], 'Alternative updated source');
    await refs.updateProjectReference(project.vaultDir, project.record.projectId, beta.referenceId, { removed: true });
    Object.assign(window, { showDirectoryPicker: async () => home });
    return { alternativeId, partB: 'component:' + partB };
  });
  await page.getByRole('button', { name: 'Open my Cadtree home', exact: true }).click();
  await page.getByRole('textbox', { name: 'Cadtree home folder address' }).fill('D:\\Cadtree');
  await page.getByRole('button', { name: 'Complete setup', exact: true }).click();
  await page.getByRole('button', { name: 'Open workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Open project', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  const workingBranch = await page.locator('.project-context-header').getAttribute('data-branch-id');
  await page.getByRole('navigation').getByRole('button', { name: 'References', exact: true }).click();
  const view = page.locator('.references-page');
  await expect(page.locator('.project-context-case')).toHaveCount(0);
  await expect(view.getByRole('combobox')).toHaveCount(2);
  await expect(view.locator('.reference-card')).toHaveCount(4);
  for (const name of ['Import reference', 'Edit details', 'Add new version', 'Use this version in project context', 'Remove from current context', 'Stop inheriting in future revisions']) await expect(view.getByRole('button', { name, exact: true })).toHaveCount(0);
  await expect(view.getByRole('combobox', { name: 'Part / file' }).locator('option')).toContainText(['All parts / files', 'A.SLDPRT', 'B.SLDPRT', 'notes.txt']);
  await view.getByRole('combobox', { name: 'Branch', exact: true }).selectOption('branch-main');
  await view.getByRole('combobox', { name: 'Part / file' }).selectOption(ids.partB);
  const search = view.getByRole('searchbox', { name: 'Search references' });
  await search.fill('Alpha');
  await expect(view).toContainText('No matching references');
  await search.fill('');
  await expect(view.locator('.reference-card')).toHaveCount(2);
  await expect(view.getByRole('button', { name: 'Download Beta requirement (Beta.txt)', exact: true })).toBeVisible();
  await view.getByRole('combobox', { name: 'Branch', exact: true }).selectOption(ids.alternativeId);
  await search.fill('Alpha updated.txt');
  await expect(view.locator('.reference-card')).toHaveCount(1);
  await expect(view).toContainText('Alternative · Rev 003');
  await expect(view).toContainText('Part: B.SLDPRT');
  await search.fill('Alpha.txt');
  await expect(view.locator('.reference-card')).toHaveCount(1);
  const event = page.waitForEvent('download');
  await view.getByRole('button', { name: 'Download Alpha requirement (Alpha.txt)', exact: true }).click();
  const download = await event;
  expect(download.suggestedFilename()).toBe('Alpha.txt');
  const stream = await download.createReadStream(), chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks)).toEqual(Buffer.from([0, 255, 13, 10, 128]));
  expect(await page.locator('.project-context-header').getAttribute('data-branch-id')).toBe(workingBranch);
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await search.fill('');
  await view.getByRole('combobox', { name: 'Branch', exact: true }).selectOption('');
  await view.getByRole('combobox', { name: 'Part / file' }).selectOption('');
  await expect(view.locator('.reference-card')).toHaveCount(4);
  // Attach fresh files through the Save revision form, then retrieve the copy
  // from both saved History and the read-only project reference browser.
  await page.getByRole('navigation').getByRole('button', { name: 'Changes', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  await expect(page.locator('.reference-selector')).toHaveCount(0);
  await page.getByRole('button', { name: '+ Attach reference files', exact: true }).click();
  const bytes = Buffer.from([0, 255, 13, 10, 128, 42]);
  await page.getByLabel('Reference files', { exact: true }).setInputFiles([
    { name: 'Clearance.pdf', mimeType: 'application/pdf', buffer: bytes },
    { name: 'Customer brief.txt', mimeType: 'text/plain', buffer: Buffer.from('Overall design intent') },
  ]);
  await page.getByRole('combobox', { name: 'Applies to Clearance.pdf', exact: true }).selectOption({ label: 'B.SLDPRT' });
  await page.getByRole('textbox', { name: 'Reference note for Clearance.pdf', exact: true }).fill('Maintain the bearing clearance');
  await page.getByRole('textbox', { name: 'Reference note for Customer brief.txt', exact: true }).fill('Whole revision intent');
  await page.getByRole('textbox', { name: /Revision summary/ }).fill('Attach client sources');
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  await expect(page.getByText(/Published and verified Rev 004/)).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('button', { name: /Rev 004:/ }).click();
  await page.getByRole('button', { name: 'Saved references', exact: true }).click();
  await expect(page.locator('.revision-detail')).toContainText('Maintain the bearing clearance');
  await expect(page.locator('.revision-detail')).toContainText('Whole revision intent');
  await expect(page.locator('.revision-detail')).toContainText('Saved by Test Engineer');
  const historyDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download Clearance.pdf', exact: true }).click();
  const historyCopy = await historyDownload;
  expect(historyCopy.suggestedFilename()).toBe('Clearance.pdf');
  const savedStream = await historyCopy.createReadStream(), savedChunks: Buffer[] = [];
  for await (const chunk of savedStream!) savedChunks.push(Buffer.from(chunk));
  expect(Buffer.concat(savedChunks)).toEqual(bytes);
  await page.getByRole('navigation').getByRole('button', { name: 'References', exact: true }).click();
  await view.getByRole('searchbox', { name: 'Search references' }).fill('Clearance.pdf');
  await expect(view.locator('.reference-card')).toHaveCount(1);
  await expect(view).toContainText('Main · Rev 004');
  await expect(view).toContainText('Part: B.SLDPRT');
  await expect(view).toContainText('Maintain the bearing clearance');
  await expect(view.getByRole('button', { name: 'Download Clearance.pdf (Clearance.pdf)', exact: true })).toBeVisible();
  // Add a reference from the References page without saving a revision.
  await view.getByRole('searchbox', { name: 'Search references' }).fill('');
  await view.getByRole('combobox', { name: 'Branch', exact: true }).selectOption('');
  await view.getByRole('combobox', { name: 'Part / file' }).selectOption('');
  const cardsBefore = await view.locator('.reference-card').count();
  await view.getByRole('button', { name: 'Add reference…', exact: true }).click();
  await view.getByLabel('Reference files', { exact: true }).setInputFiles({ name: 'Standard.pdf', mimeType: 'application/pdf', buffer: Buffer.from([1, 2, 3, 4]) });
  await view.getByRole('textbox', { name: 'Note for the new references', exact: true }).fill('Applicable standard');
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await view.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(view.getByRole('button', { name: 'Download Standard.pdf (Standard.pdf)', exact: true })).toBeVisible();
  await expect(view.locator('.reference-card')).toHaveCount(cardsBefore + 1);
  await expect(view).toContainText('Applies to the whole project');
  await expect(page.getByRole('navigation').getByRole('button', { name: 'History', exact: true })).toBeVisible();
});
