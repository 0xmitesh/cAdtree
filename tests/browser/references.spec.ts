import { test, expect } from '@playwright/test';

// OPFS checks qualify browser behaviour only; native pickers/CAD still need device testing.
for (const width of [1366, 390]) test(`project references: exact import, component context and version pinning at ${width}px`, async ({ page }) => {
  test.setTimeout(60000);
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  await page.evaluate(async () => {
    const fsPath = '/src/engine/fs-adapter.ts', homePath = '/src/engine/home-service.ts', workspacePath = '/src/engine/workspace-service.ts', revisionPath = '/src/engine/revision-service.ts';
    const [{ RealFileSystemAdapter }, homeService, workspaceService, { captureRevision }] = await Promise.all([import(fsPath), import(homePath), import(workspacePath), import(revisionPath)]);
    const root = await navigator.storage.getDirectory();
    const home = await root.getDirectoryHandle(`reference-test-${crypto.randomUUID()}`, { create: true });
    const adapter = new RealFileSystemAdapter(home); await homeService.createHome(adapter);
    const workspace = await homeService.createHomeWorkspace(adapter, 'Engineering');
    const project = await workspaceService.createProject(workspace.workspace.root, 'Actuator');
    const main = project.workingFolders['branch-main'];
    await main.writeFileText(['part.SLDPRT'], 'saved geometry');
    await captureRevision(main, project.vaultDir, { branchId: 'branch-main', summary: 'Original geometry', notes: { problem: '', modification: '', observations: '' }, workingFolders: project.workingFolders });
    await main.writeFileText(['New.SLDPRT'], 'new component');
    Object.assign(window, { showDirectoryPicker: async () => home, referenceTestVault: project.vaultDir });
  });
  await page.getByRole('button', { name: 'Open my Cadtree home', exact: true }).click();
  await page.getByRole('textbox', { name: 'Cadtree home folder address' }).fill('D:\\Cadtree');
  await page.getByRole('button', { name: 'Complete setup', exact: true }).click();
  await page.getByRole('button', { name: 'Open workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Open project', exact: true }).click();
  const nav = page.getByRole('navigation');
  await nav.getByRole('button', { name: 'References', exact: true }).click();
  await page.getByRole('button', { name: 'Import reference', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Import reference' });
  const bytes = Buffer.from([0, 255, 13, 10, 128]);
  await dialog.getByLabel('Original attachment').setInputFiles({ name: 'Requirement.pdf', mimeType: 'application/pdf', buffer: bytes });
  await dialog.getByLabel('Tags (comma separated)').fill('clearance, customer');
  await dialog.getByRole('button', { name: 'Copy and verify attachment' }).click();
  await expect(dialog).toHaveCount(0);
  const technical = page.locator('.reference-technical-details');
  await expect(technical.locator('p')).toBeHidden();
  await technical.locator('summary').click();
  await expect(technical.locator('p')).toBeVisible();
  await expect(technical).toContainText('SHA-256:');
  await technical.locator('summary').click();
  await page.getByRole('button', { name: 'Use this version in project context' }).click();
  await expect(page.getByRole('button', { name: 'Project context: this version' })).toBeDisabled();
  await nav.getByRole('button', { name: 'Changes', exact: true }).click();
  await page.getByRole('button', { name: 'Add revision reference' }).click();
  await page.getByRole('textbox', { name: 'Locator (optional)' }).fill('page 4');
  await page.getByRole('textbox', { name: 'Explanation (optional)' }).fill('Increase clearance');
  await page.getByRole('combobox', { name: 'Component (optional)' }).selectOption('path:New.SLDPRT');
  await page.getByRole('textbox', { name: /Revision summary/ }).fill('Follow requirements');
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  await nav.getByRole('button', { name: 'References', exact: true }).click();
  await page.getByRole('button', { name: 'Add new version' }).click();
  const versionDialog = page.getByRole('dialog', { name: 'Add new reference version' });
  await versionDialog.getByLabel('Original attachment').setInputFiles({ name: 'Requirement-v2.pdf', mimeType: 'application/pdf', buffer: Buffer.from('version two') });
  await versionDialog.getByRole('button', { name: 'Copy and verify attachment' }).click();
  await expect(versionDialog).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Attachment version — Requirement.pdf' }).selectOption({ label: 'Version 2: Requirement-v2.pdf' });
  await page.getByRole('button', { name: 'Use this version in project context' }).click();
  await expect(page.getByRole('button', { name: 'Project context: this version' })).toBeEnabled();
  await nav.getByRole('button', { name: 'Changes', exact: true }).click();
  await expect(page.getByText('Reference-context-only revision — no design-file bytes changed.')).toBeVisible();
  await page.getByRole('textbox', { name: /Revision summary/ }).fill('Advance project source');
  await page.getByRole('button', { name: 'Save revision', exact: true }).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false');
  await expect(page.getByRole('button', { name: 'Save revision', exact: true })).toHaveCount(0);
  await nav.getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('button', { name: /^Rev 002:/ }).click();
  await page.locator('.detail-tabs').getByRole('button', { name: "Saved references", exact: true }).click();
  await expect(page.getByText('Filename at capture: New.SLDPRT', { exact: false })).toBeVisible();
  await expect(page.getByText('Requirement-v2.pdf', { exact: true })).toHaveCount(0);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Retrieve exact attachment' }).first().click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('Requirement.pdf');
  const stream = await download.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks)).toEqual(bytes);
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
});
